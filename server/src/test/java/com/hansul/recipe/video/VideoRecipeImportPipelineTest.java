    @Test
    void deletesTheGeminiCopyWhateverGoesWrongAfterTheUpload() {
        gemini.fail(new GeminiException(Kind.QUOTA, "Gemini returned HTTP 429 RESOURCE_EXHAUSTED"));
        assertFailure(() -> pipeline().importUpload(UPLOAD_ID, UPLOAD_FILE, "video/mp4", 612, stages::add),
                "AI_QUOTA_EXCEEDED");
        assertThat(gemini.events).containsExactly("upload", "await files/abc123", "generate", "delete files/abc123");

        var failedProcessing = new FakeGeminiClient();
        failedProcessing.processingFailure = new GeminiException(Kind.FILE_PROCESSING_FAILED, "failed");
        assertFailure(() -> pipeline(failedProcessing, VideoFixtures.properties())
                .importUpload(UPLOAD_ID, UPLOAD_FILE, "video/mp4", 612, null), "AI_UNAVAILABLE");
        assertThat(failedProcessing.events).containsExactly("upload", "await files/abc123", "delete files/abc123");

        var notCooking = new FakeGeminiClient().answer(VideoFixtures.NOT_COOKING_JSON);
        assertFailure(() -> pipeline(notCooking, VideoFixtures.properties())
                .importUpload(UPLOAD_ID, UPLOAD_FILE, "video/mp4", 612, null), "NOT_A_RECIPE_VIDEO");
        assertThat(notCooking.deletedFiles).containsExactly("files/abc123");

        var rejected = new FakeGeminiClient();
        rejected.uploadFailure = new GeminiException(Kind.INVALID_ARGUMENT, "Gemini returned HTTP 400 INVALID_ARGUMENT");
        assertFailure(() -> pipeline(rejected, VideoFixtures.properties())
                .importUpload(UPLOAD_ID, UPLOAD_FILE, "video/mp4", 612, null), "VIDEO_UNAVAILABLE");
        assertThat(rejected.deletedFiles).isEmpty();
    }

