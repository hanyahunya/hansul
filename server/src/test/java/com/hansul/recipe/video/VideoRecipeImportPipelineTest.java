    void mapsTranscriptFailuresToJobCodes(Kind kind, String code) {
        var cause = new GeminiException(kind, "Gemini returned HTTP 400 INVALID_ARGUMENT");
        gemini.fail(cause);

        assertThatThrownBy(() -> pipeline().importYouTube(VIDEO_ID, stages::add))
                .isInstanceOfSatisfying(VideoImportFailure.class, failure -> {
                    assertThat(failure.code()).isEqualTo(code);
                    assertThat(failure.getCause()).isSameAs(cause);
                    assertThat(failure.getMessage()).isEqualTo(cause.getMessage());
                });
    }

