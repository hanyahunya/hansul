    @Test
    void importsAYouTubeVideoFromItsTranscriptAndDescription() {
        gemini.answer(TRANSCRIPT_JSON, 12000, 2500).answer(RECIPE_JSON, 3000, 800);

        var result = pipeline().importYouTube(VIDEO_ID, stages::add);

        assertThat(stages).containsExactly(FETCHING_METADATA, WATCHING_VIDEO, WRITING_RECIPE);
        assertThat(metadataRequests).containsExactly(VIDEO_ID);
        assertThat(gemini.requests).hasSize(2);
        assertThat(gemini.requests.get(0).media()).isEqualTo(Media.youTube(VideoFixtures.WATCH_URL));
        assertThat(gemini.requests.get(0).systemInstruction()).isEqualTo(VideoTranscriptPass.INSTRUCTIONS);
        assertThat(gemini.requests.get(1).media()).isNull();
        assertThat(gemini.requests.get(1).systemInstruction()).isEqualTo(VideoRecipeStructuringPass.INSTRUCTIONS);
        var context = mapper.readTree(gemini.requests.get(1).text());
        assertThat(context.path("videoTitle").stringValue()).isEqualTo("자취생 초간단 김치볶음밥");
        assertThat(context.path("channel").stringValue()).isEqualTo("한술키친");
        assertThat(context.path("descriptionLines")).hasSize(9);
        assertThat(context.path("segments")).hasSize(7);
        assertThat(context.has("previousIssues")).isFalse();

        assertThat(result.parserVersion()).isEqualTo("youtube-gemini-v1");
        assertThat(result.inputTokens()).isEqualTo(15000);
        assertThat(result.outputTokens()).isEqualTo(3300);
        var recipe = result.recipe();
        assertThat(recipe.title()).isEqualTo("초간단 김치볶음밥");
        assertThat(recipe.baseServings()).isEqualByComparingTo("2");
        assertThat(recipe.baseServingsText()).isEqualTo("2인분");
        assertThat(recipe.description()).isEqualTo(VideoFixtures.DESCRIPTION);
        assertThat(recipe.totalTimeText()).isNull();
        assertThat(recipe.primaryImageUrl()).isEqualTo(VideoFixtures.THUMBNAIL);
        assertThat(recipe.sourceFormat()).isEqualTo("VIDEO_AI_TRANSCRIPT");
        assertThat(recipe.sourceEvidenceLocator()).isEqualTo("youtube:AbCdEfGhIjK");
        assertThat(recipe.video()).isEqualTo(
                new ParsedVideo("YOUTUBE", VIDEO_ID, VideoFixtures.WATCH_URL, 95, "한술키친", true));
        assertThat(recipe.warnings()).containsExactly(AI_WARNING);
        assertThat(recipe.ingredients()).extracting(ParsedIngredient::name, ParsedIngredient::quantityText)
                .containsExactly(
                        tuple("신김치", "1컵"),
                        tuple("밥", "2공기"),
                        tuple("대파", "1대"),
                        tuple("식용유", "2스푼"),
                        tuple("설탕", "0.5스푼"),
                        tuple("참기름", "약간"));
        assertThat(recipe.steps()).extracting(ParsedStep::text).containsExactly(
                "대파 1대를 송송 썰어주세요.",
                "팬에 식용유 2스푼을 두르고 대파를 넣어 파기름을 내주세요.",
                VideoFixtures.SAID_THREE_MINUTES,
                "설탕 0.5스푼을 넣어 신맛을 줄여주세요.",
                "밥 2공기를 넣고 잘 섞어주세요.",
                "참기름을 한 바퀴 둘러 마무리해주세요.");
        assertThat(recipe.steps().get(2)).isEqualTo(new ParsedStep(3, "신김치 한 컵을 넣고 중불에서 삼 분 정도 볶아 줍니다",
                VideoFixtures.SAID_THREE_MINUTES, null,
                new SourceEvidence(SourceType.VIDEO_SEGMENT, "segments:s4@28-45"), 28, 45, 40));

        var raw = mapper.readTree(recipe.rawStructuredData());
        assertThat(raw.propertyNames()).containsExactly("pipelineVersion", "model", "language", "segments");
        assertThat(raw.path("pipelineVersion").stringValue()).isEqualTo("youtube-gemini-v1");
        assertThat(raw.path("model").stringValue()).isEqualTo("gemini-test");
        assertThat(raw.path("language").stringValue()).isEqualTo("ko");
        assertThat(raw.path("segments")).hasSize(7);
        assertThat(raw.path("segments").get(3)).isEqualTo(mapper.readTree("""
                {"id": "s4", "startSeconds": 28, "endSeconds": 45,
                 "speech": "신김치 한 컵을 넣고 중불에서 삼 분 정도 볶아 줍니다", "screenText": ""}"""));
    }

    @Test
    void asksForTheRecipeOnceMoreWithThePreviousIssues() {
        gemini.answer(TRANSCRIPT_JSON, 12000, 2500)
                .answer(UNGROUNDED_RECIPE_JSON, 3000, 800)
                .answer(RECIPE_JSON, 3300, 820);

        var result = pipeline().importYouTube(VIDEO_ID, stages::add);

        assertThat(gemini.requests).hasSize(3);
        var retry = mapper.readTree(gemini.requests.get(2).text());
        assertThat(retry.path("previousIssues")).singleElement().satisfies(issue -> assertThat(issue.stringValue())
                .isEqualTo("steps[2] \"신김치 1컵을 넣고 중불에서 5분 볶아주세요.\": 숫자(5)가 근거 구간(s4)에 없습니다."));
        assertThat(retry.path("segments")).hasSize(7);
        assertThat(result.recipe().steps().get(2).text()).isEqualTo(VideoFixtures.SAID_THREE_MINUTES);
        assertThat(result.recipe().warnings()).containsExactly(AI_WARNING);
        assertThat(result.inputTokens()).isEqualTo(18300);
        assertThat(result.outputTokens()).isEqualTo(4120);
        assertThat(stages).containsExactly(FETCHING_METADATA, WATCHING_VIDEO, WRITING_RECIPE);
    }

