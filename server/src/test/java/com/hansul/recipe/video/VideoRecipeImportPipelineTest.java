    private VideoRecipeImportPipeline pipeline() {
        return pipeline(gemini, VideoFixtures.properties());
    }

    private VideoRecipeImportPipeline pipeline(GeminiClient client, VideoImportProperties properties) {
        return new GeminiVideoRecipeImportPipeline(
                client,
                videoId -> {
                    metadataRequests.add(videoId);
                    return metadata.fetch(videoId);
                },
                new VideoTranscriptPass(client, properties),
                new VideoRecipeStructuringPass(client, mapper, properties),
                new VideoRecipeValidator(new IngredientTextParser()),
                mapper,
                properties
        );
    }

    private static void assertFailure(ThrowingCallable call, String code) {
        Consumer<VideoImportFailure> hasCode = failure -> assertThat(failure.code()).isEqualTo(code);
        assertThatThrownBy(call).isInstanceOfSatisfying(VideoImportFailure.class, hasCode::accept);
    }
