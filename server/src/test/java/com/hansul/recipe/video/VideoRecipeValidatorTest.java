    @Test
    void normalizesAndCompactsTextBeforeMatchingQuotes() {
        assertThat(VideoText.normalize("  양파​ 한 개﻿를\t\n 썰어요  ")).isEqualTo("양파 한 개를 썰어요");
        assertThat(VideoText.normalize(Normalizer.normalize("양파", Normalizer.Form.NFD))).isEqualTo("양파");
        assertThat(VideoText.normalize("간장\u0000 1T")).isEqualTo("간장 1T");
        assertThat(VideoText.normalize(null)).isEmpty();
        assertThat(VideoText.compact("양파 1/2개! (중간 크기)")).isEqualTo("양파12개중간크기");
        assertThat(VideoText.compact("Olive Oil 2T")).isEqualTo("oliveoil2t");

        assertThat(VideoText.quoteMatches("양 파, 한 개!", "먼저 양파 한 개를 썰어요")).isTrue();
        assertThat(VideoText.quoteMatches("양", "양파")).isFalse();
        assertThat(VideoText.quoteMatches("...", "양파")).isFalse();
        assertThat(VideoText.quoteMatches("대파 두 대", "대파 한 대")).isFalse();
    }

    @Test
    void clampsWithoutCuttingANumberInTwo() {
        assertThat(VideoText.clamp("양파 150g", 6)).isEqualTo("양파 150");
        assertThat(VideoText.clamp("양파 1500g", 5)).isEqualTo("양파");
        assertThat(VideoText.clamp("양파150g을", 4)).isEqualTo("양파");
        assertThat(VideoText.clamp("물 1.5L", 4)).isEqualTo("물");
        assertThat(VideoText.clamp("가나다라 마바사", 6)).isEqualTo("가나다라");
        assertThat(VideoText.clamp("짧은 글", 10)).isEqualTo("짧은 글");
        assertThat(VideoText.clamp("양파😀양파", 3)).isEqualTo("양파");
    }

    private static VideoRecipeDraft servingsDraft(String text, String source, String ref, String quote) {
        return VideoFixtures.draft(replace(RECIPE_JSON,
                "\"servings\": {\"text\": \"2인분\", \"source\": \"DESCRIPTION\", \"ref\": \"d2\", \"quote\": \"2인분\"}",
                "\"servings\": {\"text\": \"%s\", \"source\": \"%s\", \"ref\": \"%s\", \"quote\": \"%s\"}"
                        .formatted(text, source, ref, quote)));
    }

    private static SourceEvidence description(String ref) {
        return new SourceEvidence(SourceType.VIDEO_DESCRIPTION, "description:" + ref);
    }

    private static SourceEvidence segments(String locator) {
        return new SourceEvidence(SourceType.VIDEO_SEGMENT, locator);
    }

    private static String replace(String json, String... pairs) {
        var result = json;
        for (var index = 0; index < pairs.length; index += 2) {
            if (!result.contains(pairs[index])) {
                throw new IllegalArgumentException("Fixture does not contain " + pairs[index]);
            }
            result = result.replace(pairs[index], pairs[index + 1]);
        }
        return result;
    }
