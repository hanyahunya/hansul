    @Test
    void readsServingsOnlyFromEvidenceOfTheDeclaredKind() {
        var wrongKind = servingsDraft("2인분", "SEGMENT", "d2", "2인분");
        var unsaid = servingsDraft("4인분", "DESCRIPTION", "d2", "2인분");
        var none = servingsDraft("2인분", "NONE", "", "");

        assertThat(validator.issues(wrongKind, sources))
                .containsExactly("servings: source SEGMENT에 맞는 근거 id(d2)가 없습니다.");
        assertThat(validator.toRecipe(wrongKind, sources, ENVELOPE).baseServingsText()).isNull();
        assertThat(validator.issues(unsaid, sources)).containsExactly("servings: 숫자(4)가 근거(d2)에 없습니다.");
        assertThat(validator.toRecipe(unsaid, sources, ENVELOPE).baseServings()).isNull();
        assertThat(validator.issues(none, sources)).isEmpty();
        assertThat(validator.toRecipe(none, sources, ENVELOPE).baseServingsText()).isNull();

        var range = new VideoSources(VideoFixtures.segments(), "[재료] 2~3인분");
        var recipe = validator.toRecipe(servingsDraft("2~3인분", "DESCRIPTION", "d1", "2~3인분"), range, ENVELOPE);
        assertThat(recipe.baseServingsText()).isEqualTo("2~3인분");
        assertThat(recipe.baseServings()).isNull();

        var spoken = new VideoSources(List.of(new VideoTranscript.Segment(
                "s1", 0, 30, "이 양이면 세 인분 나와요 양파를 볶아 줄게요", "")), null);
        var spokenRecipe = validator.toRecipe(VideoFixtures.draft("""
                {"title": "양파볶음", "servings": {"text": "3인분", "source": "SEGMENT", "ref": "s1", "quote": "세 인분 나와요"},
                 "ingredients": [],
                 "steps": [{"text": "양파를 볶아주세요.", "segmentIds": ["s1"], "startSeconds": 0, "endSeconds": 30,
                            "keyFrameSeconds": 15, "quote": "양파를 볶아"}]}"""), spoken, ENVELOPE);
        assertThat(spokenRecipe.baseServings()).isEqualTo(new BigDecimal("3"));
        assertThat(spokenRecipe.baseServingsText()).isEqualTo("3인분");
    }

