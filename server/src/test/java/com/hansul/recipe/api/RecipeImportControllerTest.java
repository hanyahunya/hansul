    @Test
    void writesExactlyTheRecipeBodiesTheAndroidAppDecodes() throws Exception {
        when(recipeImportService.getRecipe(RECIPE_ID)).thenReturn(youTubeRecipe());
        when(recipeImportService.getRecipe(UPLOAD_RECIPE_ID)).thenReturn(uploadedVideoRecipe());
        when(recipeImportService.getRecipe(WEB_PAGE_RECIPE_ID)).thenReturn(webPageRecipeWithNaverTvVideo());

        mockMvc.perform(get("/v1/recipes/{id}", RECIPE_ID).with(jwt()))
                .andExpect(status().isOk())
                .andExpect(content().json(YOUTUBE_RECIPE_JSON, JsonCompareMode.STRICT));
        mockMvc.perform(get("/v1/recipes/{id}", UPLOAD_RECIPE_ID).with(jwt()))
                .andExpect(status().isOk())
                .andExpect(content().json(UPLOAD_RECIPE_JSON, JsonCompareMode.STRICT));
        mockMvc.perform(get("/v1/recipes/{id}", WEB_PAGE_RECIPE_ID).with(jwt()))
                .andExpect(status().isOk())
                .andExpect(content().json(WEB_PAGE_RECIPE_JSON, JsonCompareMode.STRICT));
    }

    @Test
    void answersUnsupportedVideoPlatformsWith422() throws Exception {
        var url = "https://www.instagram.com/reel/C1a2b3c4d5e/";
        when(recipeImportService.importRecipe(url)).thenThrow(new UnsupportedVideoPlatformException("Instagram"));

        mockMvc.perform(post("/v1/recipe-imports")
                        .with(jwt())
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"url\":\"" + url + "\"}"))
                .andExpect(status().is(422))
                .andExpect(jsonPath("$.code").value("VIDEO_LINK_NOT_SUPPORTED"))
                .andExpect(jsonPath("$.message").isNotEmpty())
                .andExpect(jsonPath("$.timestamp").isNotEmpty());
    }

    @Test
    void answersYouTubeLinksOnTheSynchronousEndpointWithVideoImportRequiresJob() throws Exception {
        when(recipeImportService.importRecipe(WATCH_URL)).thenThrow(new RecipeImportException(
                HttpStatus.BAD_REQUEST,
                "VIDEO_IMPORT_REQUIRES_JOB",
                "Video recipes are imported through POST /v1/recipe-import-jobs"
        ));

        mockMvc.perform(post("/v1/recipe-imports")
                        .with(jwt())
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"url\":\"" + WATCH_URL + "\"}"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("VIDEO_IMPORT_REQUIRES_JOB"));
    }

