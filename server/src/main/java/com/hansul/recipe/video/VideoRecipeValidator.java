package com.hansul.recipe.video;

import com.hansul.recipe.domain.ParsedIngredient;
import com.hansul.recipe.domain.ParsedRecipe;
import com.hansul.recipe.domain.ParsedStep;
import com.hansul.recipe.domain.ParsedVideo;
import com.hansul.recipe.domain.SourceEvidence;
import com.hansul.recipe.domain.SourceEvidence.SourceType;
import com.hansul.recipe.infrastructure.parser.IngredientTextParser;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import org.springframework.stereotype.Component;

/**
 * Deterministic checks of a pass 2 draft against the transcript and the description. A first draft yields
 * issues for the model's second attempt; whatever still fails after that falls back to the video's own words
 * or is left out, so every quote and every number of the recipe can be found in its evidence.
 */
@Component
class VideoRecipeValidator {

    static final String AI_WARNING =
            "Recipe generated by AI from the video's speech and on-screen text; verify amounts and times in the video.";
    static final String VERBATIM_WARNING =
            "Some steps show the video transcript verbatim because the summary could not be verified.";
    static final String AMOUNT_WARNING = "Some ingredient amounts could not be verified; check them in the video.";
    static final String DEFAULT_TITLE = "영상 레시피";
    private static final int MAX_TITLE = 200;
    private static final int MAX_STEP_TEXT = 300;
    private static final int MAX_STEP_RAW_TEXT = 1000;
    private static final int MAX_NAME = 100;
    private static final int MAX_QUANTITY = 100;
    private static final int MAX_SERVINGS_TEXT = 200;
    private static final int MAX_QUOTE = 500;
    private static final int MAX_DESCRIPTION = 4000;
    private static final int MAX_LOCATOR_REFS = 400;
    private static final int MAX_ISSUES = 40;
    private static final int MAX_EXCERPT = 40;
    private static final double TIME_SLACK_SECONDS = 5;
    private static final BigDecimal MAX_SERVINGS = BigDecimal.valueOf(1000);

    private final IngredientTextParser ingredientTextParser;

    VideoRecipeValidator(IngredientTextParser ingredientTextParser) {
        this.ingredientTextParser = ingredientTextParser;
    }

    /** Problems of a first draft, worded for the model's second attempt; empty when the draft is sound. */
    List<String> issues(VideoRecipeDraft draft, VideoSources sources) {
        return evaluate(draft, sources).issues();
    }

    /** Throws {@link VideoImportFailure} RECIPE_EXTRACTION_FAILED when no step is backed by the transcript. */
    ParsedRecipe toRecipe(VideoRecipeDraft draft, VideoSources sources, Envelope envelope) {
        var evaluation = evaluate(draft, sources);
        if (evaluation.steps().isEmpty()) {
            throw new VideoImportFailure(
                    VideoImportFailure.RECIPE_EXTRACTION_FAILED,
                    "No recipe step could be verified against the video transcript"
            );
        }
        var warnings = new LinkedHashSet<String>();
        warnings.add(AI_WARNING);
        warnings.addAll(envelope.warnings());
        warnings.addAll(evaluation.warnings());
        return new ParsedRecipe(
                title(draft.title(), envelope.metadataTitle()),
                evaluation.servings().count(),
                evaluation.servings().text(),
                VideoText.multiline(envelope.description(), MAX_DESCRIPTION),
                null,
                envelope.primaryImageUrl(),
                evaluation.ingredients(),
                evaluation.steps(),
                ParsedRecipe.VIDEO_AI_SOURCE_FORMAT,
                envelope.sourceEvidenceLocator(),
                envelope.rawStructuredData(),
                List.copyOf(warnings),
                envelope.video()
        );
    }

    /** What the recipe says about its origin; none of it is checked against the transcript. */
    record Envelope(
            String sourceEvidenceLocator,
            String metadataTitle,
            String description,
            String primaryImageUrl,
            ParsedVideo video,
            String rawStructuredData,
            List<String> warnings
    ) {
        Envelope {
            warnings = List.copyOf(warnings);
        }
    }

    // One pass decides both the issues and the fallbacks, so a draft without issues is used exactly as written.
    private Evaluation evaluate(VideoRecipeDraft draft, VideoSources sources) {
        var issues = new Issues();
        var warnings = new LinkedHashSet<String>();
        var steps = steps(draft.steps(), sources, issues, warnings);
        var ingredients = ingredients(draft.ingredients(), sources, issues, warnings);
        var servings = servings(draft.servings(), sources, issues);
        return new Evaluation(issues.list(), steps, ingredients, servings, List.copyOf(warnings));
    }

    private List<ParsedStep> steps(
            List<VideoRecipeDraft.Step> drafts,
            VideoSources sources,
            Issues issues,
            Set<String> warnings
    ) {
        if (drafts.isEmpty()) {
            issues.add("steps: 단계가 하나도 없습니다.");
        }
        var accepted = new ArrayList<AcceptedStep>();
        for (var index = 0; index < Math.min(drafts.size(), VideoRecipeStructuringPass.MAX_STEPS); index++) {
            var draft = drafts.get(index);
            var text = VideoText.normalize(draft.text());
            var label = "steps[" + index + "]" + excerpt(text);
            var ids = draft.segmentIds().stream()
                    .map(VideoText::normalize)
                    .filter(id -> !id.isEmpty())
                    .distinct()
                    .toList();
            var refs = new ArrayList<VideoTranscript.Segment>();
            var unknown = new ArrayList<String>();
            for (var id : ids) {
                sources.segment(id).ifPresentOrElse(refs::add, () -> unknown.add(id));
            }
            if (ids.isEmpty()) {
                issues.add(label + ": segmentIds가 비어 있습니다.");
            }
            if (!unknown.isEmpty()) {
                issues.add(label + ": 없는 구간 id(" + String.join(", ", unknown) + ")를 참조했습니다.");
            }
            if (refs.isEmpty()) {
                continue;
            }
            refs.sort(Comparator.comparingInt(sources::position));
            var refList = refs.stream().map(VideoTranscript.Segment::id).collect(Collectors.joining(", "));
            var sourceTexts = refs.stream().map(VideoTranscript.Segment::sourceText).toList();

            var verified = true;
            if (!VideoText.quoteMatches(draft.quote(), String.join("\n", sourceTexts))) {
                issues.add(label + ": quote가 참조한 구간(" + refList + ")의 speech나 screenText에 그대로 있지 않습니다.");
                verified = false;
            }
            if (text.isEmpty()) {
                issues.add(label + ": text가 비어 있습니다.");
                verified = false;
            } else if (text.length() > MAX_STEP_TEXT) {
                issues.add(label + ": text가 " + MAX_STEP_TEXT + "자를 넘습니다.");
                verified = false;
            }
            var missing = VideoNumberGrounding.missingNumbers(text, sourceTexts);
            if (!missing.isEmpty()) {
                issues.add(label + ": 숫자(" + format(missing) + ")가 근거 구간(" + refList + ")에 없습니다.");
                verified = false;
            }
            if (!verified) {
                text = verbatim(refs);
                warnings.add(VERBATIM_WARNING);
            }
            var step = accept(draft, refs, text, sources);
            if (step.besideRefs()) {
                issues.add(label + ": startSeconds와 endSeconds가 참조한 구간(" + refList + ", " + seconds(refs) + ")과 "
                        + "맞지 않습니다.");
            }
            accepted.add(step);
        }

        accepted.sort(Comparator.comparingDouble(AcceptedStep::start));
        var steps = new ArrayList<ParsedStep>();
        for (var step : accepted) {
            steps.add(new ParsedStep(
                    steps.size() + 1,
                    step.rawText(),
                    step.text(),
                    null,
                    new SourceEvidence(SourceType.VIDEO_SEGMENT, step.locator()),
                    step.startSeconds(),
                    step.endSeconds(),
                    step.keyFrameSeconds()
            ));
        }
        return steps;
    }

    // Times stay near the cited segments: within 5 s of them, never negative, key frame inside the step.
    private static AcceptedStep accept(
            VideoRecipeDraft.Step draft,
            List<VideoTranscript.Segment> refs,
            String text,
            VideoSources sources
    ) {
        var firstStart = firstStart(refs);
        var lastEnd = lastEnd(refs);
        var low = Math.max(0, firstStart - TIME_SLACK_SECONDS);
        var high = lastEnd + TIME_SLACK_SECONDS;
        double start = draft.startSeconds() == null ? firstStart : draft.startSeconds();
        double end = draft.endSeconds() == null ? lastEnd : draft.endSeconds();
        if (start > end) {
            start = firstStart;
            end = lastEnd;
        }
        start = Math.clamp(start, low, high);
        end = Math.clamp(end, low, high);
        // Times that miss the cited segments (a neighbouring step's, say) clamp to one instant; use the segments'.
        var besideRefs = end <= start && lastEnd > firstStart;
        if (besideRefs) {
            start = firstStart;
            end = lastEnd;
        }
        var keyFrame = draft.keyFrameSeconds();
        double key = keyFrame == null || keyFrame < start || keyFrame > end ? (start + end) / 2 : keyFrame;

        var startSeconds = (int) Math.floor(start);
        var endSeconds = (int) Math.ceil(end);
        return new AcceptedStep(
                start,
                startSeconds,
                endSeconds,
                (int) Math.round(key),
                text,
                rawText(refs),
                "segments:" + refRanges(refs, sources) + "@" + startSeconds + "-" + endSeconds,
                besideRefs
        );
    }

    private static double firstStart(List<VideoTranscript.Segment> refs) {
        return refs.stream().mapToDouble(VideoTranscript.Segment::startSeconds).min().orElseThrow();
    }

    private static double lastEnd(List<VideoTranscript.Segment> refs) {
        return refs.stream().mapToDouble(VideoTranscript.Segment::endSeconds).max().orElseThrow();
    }

    /** {@code 28~45초}, as the transcript gives the times of the cited segments. */
    private static String seconds(List<VideoTranscript.Segment> refs) {
        return plainSeconds(firstStart(refs)) + "~" + plainSeconds(lastEnd(refs)) + "초";
    }

    private static String plainSeconds(double value) {
        return BigDecimal.valueOf(value).stripTrailingZeros().toPlainString();
    }

    private List<ParsedIngredient> ingredients(
            List<VideoRecipeDraft.Ingredient> drafts,
            VideoSources sources,
            Issues issues,
            Set<String> warnings
    ) {
        var ingredients = new ArrayList<ParsedIngredient>();
        var names = new HashSet<String>();
        for (var index = 0; index < Math.min(drafts.size(), VideoRecipeStructuringPass.MAX_INGREDIENTS); index++) {
            var draft = drafts.get(index);
            var name = VideoText.normalize(draft.name());
            var quantity = VideoText.normalize(draft.quantityText());
            var ref = VideoText.normalize(draft.ref());
            var label = "ingredients[" + index + "]" + excerpt(name);
            var key = VideoText.compact(name);
            if (key.isEmpty()) {
                issues.add(label + ": name이 비어 있습니다.");
                continue;
            }
            if (name.length() > MAX_NAME) {
                issues.add(label + ": name이 " + MAX_NAME + "자를 넘습니다.");
                continue;
            }

            var source = sources.source(ref);
            if (source.isEmpty()) {
                issues.add(label + ": 없는 근거 id(" + (ref.isEmpty() ? "빈 값" : ref) + ")를 참조했습니다.");
            }
            var quoted = source.isPresent() && VideoText.quoteMatches(draft.quote(), source.get().text());
            if (source.isPresent() && !quoted) {
                issues.add(label + ": quote가 근거(" + ref + ")에 그대로 있지 않습니다.");
            }

            VideoSources.Source evidence;
            String rawText;
            var verifiedQuantity = "";
            if (quoted) {
                evidence = source.get();
                rawText = VideoText.clamp(VideoText.normalize(draft.quote()), MAX_QUOTE);
                var missing = VideoNumberGrounding.missingAmounts(quantity, List.of(evidence.text()));
                if (quantity.length() > MAX_QUANTITY) {
                    issues.add(label + ": quantityText가 " + MAX_QUANTITY + "자를 넘습니다.");
                } else if (!missing.isEmpty()) {
                    issues.add(label + ": 분량" + excerpt(quantity) + "의 숫자(" + format(missing)
                            + ")가 근거(" + ref + ")에 없습니다.");
                } else {
                    verifiedQuantity = quantity;
                }
            } else {
                // Without evidence of its own an ingredient survives only by name, and only if the video says it.
                var mention = sources.firstContaining(key);
                if (mention.isEmpty()) {
                    continue;
                }
                evidence = mention.get();
                rawText = name;
            }
            if (!names.add(key)) {
                continue;
            }
            if (!verifiedQuantity.equals(quantity)) {
                warnings.add(AMOUNT_WARNING);
            }
            ingredients.add(ingredient(ingredients.size() + 1, rawText, name, verifiedQuantity, evidence));
        }
        return ingredients;
    }

    private ParsedIngredient ingredient(
            int position,
            String rawText,
            String name,
            String quantity,
            VideoSources.Source source
    ) {
        var evidence = source.fromDescription()
                ? new SourceEvidence(SourceType.VIDEO_DESCRIPTION, "description:" + source.ref())
                : new SourceEvidence(SourceType.VIDEO_SEGMENT, "segment:" + source.ref());
        BigDecimal amount = null;
        String unit = null;
        String warning = null;
        if (!quantity.isEmpty()) {
            // Reused only when the page parser splits "name quantity" back into exactly these two parts.
            var parsed = ingredientTextParser.parse(position, name + " " + quantity, evidence);
            if (name.equals(parsed.name()) && quantity.equals(parsed.quantityText())) {
                amount = parsed.normalizedAmount();
                unit = parsed.normalizedUnit();
                warning = parsed.normalizationWarning();
            }
        }
        return new ParsedIngredient(position, rawText, name, quantity, amount, unit, warning, evidence);
    }

    private static Servings servings(VideoRecipeDraft.Servings draft, VideoSources sources, Issues issues) {
        var kind = VideoText.normalize(draft.source()).toUpperCase(Locale.ROOT);
        if (kind.isEmpty() || kind.equals("NONE")) {
            return Servings.UNKNOWN;
        }
        if (!kind.equals("DESCRIPTION") && !kind.equals("SEGMENT")) {
            issues.add("servings: source는 DESCRIPTION, SEGMENT, NONE 중 하나여야 합니다.");
            return Servings.UNKNOWN;
        }
        var ref = VideoText.normalize(draft.ref());
        var source = sources.source(ref)
                .filter(candidate -> candidate.fromDescription() == kind.equals("DESCRIPTION"));
        if (source.isEmpty()) {
            issues.add("servings: source " + kind + "에 맞는 근거 id(" + (ref.isEmpty() ? "빈 값" : ref) + ")가 없습니다.");
            return Servings.UNKNOWN;
        }
        if (!VideoText.quoteMatches(draft.quote(), source.get().text())) {
            issues.add("servings: quote가 근거(" + ref + ")에 그대로 있지 않습니다.");
            return Servings.UNKNOWN;
        }
        var text = VideoText.normalize(draft.text());
        if (text.isEmpty() || text.length() > MAX_SERVINGS_TEXT) {
            issues.add("servings: text는 1~" + MAX_SERVINGS_TEXT + "자여야 합니다.");
            return Servings.UNKNOWN;
        }
        var missing = VideoNumberGrounding.missingAmounts(text, List.of(source.get().text()));
        if (!missing.isEmpty()) {
            issues.add("servings: 숫자(" + format(missing) + ")가 근거(" + ref + ")에 없습니다.");
            return Servings.UNKNOWN;
        }
        return new Servings(servingCount(text), text);
    }

    // "2인분" scales; "2~3인분" keeps its text but has no single count. Every number read here was checked above.
    private static BigDecimal servingCount(String text) {
        var numbers = VideoNumberGrounding.numbersIn(text);
        if (numbers.isEmpty()) {
            numbers = VideoNumberGrounding.groundedNumbers(text);
        }
        if (numbers.size() != 1) {
            return null;
        }
        var count = numbers.iterator().next();
        if (count.signum() <= 0 || count.compareTo(MAX_SERVINGS) > 0) {
            return null;
        }
        return count.scale() < 0 ? count.setScale(0) : count;
    }

    private static String title(String draftTitle, String metadataTitle) {
        var title = VideoText.clamp(VideoText.normalize(draftTitle), MAX_TITLE);
        if (title.isEmpty()) {
            title = VideoText.clamp(VideoText.normalize(metadataTitle), MAX_TITLE);
        }
        return title.isEmpty() ? DEFAULT_TITLE : title;
    }

    // The fallback text quotes the video: speech, or the on-screen text where nothing was said.
    private static String verbatim(List<VideoTranscript.Segment> refs) {
        var text = refs.stream()
                .map(segment -> segment.speech().isEmpty() ? segment.screenText() : segment.speech())
                .collect(Collectors.joining(" "));
        return VideoText.clamp(VideoText.normalize(text), MAX_STEP_TEXT);
    }

    private static String rawText(List<VideoTranscript.Segment> refs) {
        var text = refs.stream()
                .flatMap(segment -> Stream.of(segment.speech(), segment.screenText()))
                .filter(part -> !part.isEmpty())
                .collect(Collectors.joining("\n"));
        return VideoText.clamp(text, MAX_STEP_RAW_TEXT);
    }

    /** {@code s3-s4} for neighbouring segments, {@code s3-s4,s7} when the step skips some. */
    private static String refRanges(List<VideoTranscript.Segment> refs, VideoSources sources) {
        var runs = new ArrayList<String>();
        var first = refs.getFirst();
        var previous = first;
        for (var segment : refs.subList(1, refs.size())) {
            if (sources.position(segment) != sources.position(previous) + 1) {
                runs.add(run(first, previous));
                first = segment;
            }
            previous = segment;
        }
        runs.add(run(first, previous));
        var ranges = String.join(",", runs);
        return ranges.length() <= MAX_LOCATOR_REFS ? ranges : run(refs.getFirst(), refs.getLast());
    }

    private static String run(VideoTranscript.Segment first, VideoTranscript.Segment last) {
        return first.id().equals(last.id()) ? first.id() : first.id() + "-" + last.id();
    }

    private static String excerpt(String text) {
        return text.isEmpty() ? "" : " \"" + VideoText.clamp(text, MAX_EXCERPT) + "\"";
    }

    private static String format(Set<BigDecimal> numbers) {
        return numbers.stream().map(BigDecimal::toPlainString).collect(Collectors.joining(", "));
    }

    private record Evaluation(
            List<String> issues,
            List<ParsedStep> steps,
            List<ParsedIngredient> ingredients,
            Servings servings,
            List<String> warnings
    ) {
    }

    private record AcceptedStep(
            double start,
            int startSeconds,
            int endSeconds,
            int keyFrameSeconds,
            String text,
            String rawText,
            String locator,
            boolean besideRefs
    ) {
    }

    private record Servings(BigDecimal count, String text) {
        static final Servings UNKNOWN = new Servings(null, null);
    }

    private static final class Issues {
        private final List<String> issues = new ArrayList<>();

        void add(String issue) {
            if (issues.size() < MAX_ISSUES) {
                issues.add(issue);
            }
        }

        List<String> list() {
            return List.copyOf(issues);
        }
    }
}
